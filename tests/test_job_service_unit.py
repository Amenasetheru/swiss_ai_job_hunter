def test_service_get_missing_job_raises_without_transaction_change() -> None:
    """Verify read-only absence handling does not commit or roll back."""

    service, session, repository = _build_service()
    missing_id = uuid4()

    repository.get_by_id.return_value = None

    with pytest.raises(JobNotFoundError) as error_info:
        service.get_job(missing_id)

    repository.get_by_id.assert_called_once_with(missing_id)
    assert error_info.value.job_id == missing_id

    session.commit.assert_not_called()
    session.rollback.assert_not_called()


def test_service_list_delegates_pagination_and_builds_response() -> None:
    """Verify pagination calls and public collection construction."""

    service, session, repository = _build_service()

    jobs = [
        _build_persisted_job(
            external_id=f"unit-list-{index}",
            title=f"Unit AI Engineer {index}",
            url=f"https://example.com/jobs/unit-list-{index}",
        )
        for index in range(2)
    ]

    repository.list.return_value = jobs
    repository.count.return_value = 7

    page = service.list_jobs(
        offset=2,
        limit=2,
    )

    repository.list.assert_called_once_with(
        offset=2,
        limit=2,
    )
    repository.count.assert_called_once_with()

    assert len(page.items) == 2
    assert page.total == 7
    assert page.offset == 2
    assert page.limit == 2

    session.commit.assert_not_called()
    session.rollback.assert_not_called()


def test_service_update_applies_only_provided_fields_and_commits() -> None:
    """Verify partial updates preserve omitted ORM attributes."""

    service, session, repository = _build_service()

    persisted_job = _build_persisted_job(
        title="Original Unit Engineer",
    )
    original_company_name = persisted_job.company_name
    original_location = persisted_job.location

    repository.get_by_id.return_value = persisted_job
    repository.update.return_value = persisted_job

    update_data = JobUpdate.model_validate(
        {
            "title": "Updated Unit Engineer",
            "is_active": False,
        }
    )

    response = service.update_job(
        persisted_job.id,
        update_data,
    )

    repository.get_by_id.assert_called_once_with(persisted_job.id)
    repository.update.assert_called_once_with(persisted_job)

    session.commit.assert_called_once_with()
    session.refresh.assert_called_once_with(persisted_job)
    session.rollback.assert_not_called()

    assert persisted_job.title == "Updated Unit Engineer"
    assert persisted_job.is_active is False
    assert persisted_job.company_name == original_company_name
    assert persisted_job.location == original_location

    assert response.title == "Updated Unit Engineer"
    assert response.is_active is False


