def _build_job_create(
    *,
    external_id: str = "unit-job-123",
    title: str = "Unit Test AI Engineer",
    url: str = "https://example.com/jobs/unit-job-123",
) -> JobCreate:
    """Build one valid JobCreate schema for isolated service tests."""

    return JobCreate.model_validate(
        {
            "source": "unit_test",
            "external_id": external_id,
            "title": title,
            "company_name": "Swiss Unit Bank",
            "location": "Geneva, Switzerland",
            "description": "Validate isolated Job Service business behavior.",
            "employment_type": "full_time",
            "seniority_level": "senior",
            "workplace_type": "hybrid",
            "url": url,
            "posted_at": "2026-07-24T09:00:00+02:00",
        }
    )


def _build_persisted_job(
    *,
    job_id: UUID | None = None,
    external_id: str = "persisted-unit-job",
    title: str = "Persisted AI Engineer",
    url: str = "https://example.com/jobs/persisted-unit-job",
) -> Job:
    """Build one ORM Job populated like a record returned by PostgreSQL."""

    current_time = datetime.now(UTC)

    return Job(
        id=job_id or uuid4(),
        source="unit_test",
        external_id=external_id,
        title=title,
        company_name="Swiss Unit Bank",
        location="Zurich, Switzerland",
        description="Represent a persisted Job during isolated service tests.",
        employment_type="full_time",
        seniority_level="senior",
        workplace_type="hybrid",
        url=url,
        posted_at=current_time,
        discovered_at=current_time,
        is_active=True,
        created_at=current_time,
        updated_at=current_time,
    )


def _build_service() -> tuple[JobService, MagicMock, MagicMock]:
    """Build a JobService with mocked transaction and repository dependencies."""

    session = MagicMock(spec=Session)
    repository = MagicMock(spec=JobRepository)

    service = JobService(
        session=session,
        repository=repository,
    )

    return service, session, repository


def test_service_create_coordinates_repository_and_commit() -> None:
    """Verify successful creation, commit, refresh, and response conversion."""

    service, session, repository = _build_service()
    job_data = _build_job_create()

    def persist_job(job: Job) -> Job:
        """Simulate values normally generated by SQLAlchemy and PostgreSQL."""

        current_time = datetime.now(UTC)

        job.id = uuid4()
        job.discovered_at = current_time
        job.is_active = True
        job.created_at = current_time
        job.updated_at = current_time

        return job

    repository.create.side_effect = persist_job

    response = service.create_job(job_data)

    repository.create.assert_called_once()
    created_entity = repository.create.call_args.args[0]

    assert isinstance(created_entity, Job)
    assert created_entity.title == job_data.title
    assert created_entity.url == str(job_data.url)

    session.commit.assert_called_once_with()
    session.refresh.assert_called_once_with(created_entity)
    session.rollback.assert_not_called()

    assert response.id == created_entity.id
    assert response.title == job_data.title


def test_service_create_rolls_back_and_translates_duplicate() -> None:
    """Verify duplicate persistence failures become business exceptions."""

    service, session, repository = _build_service()

    repository.create.side_effect = DuplicateJobError(constraint_name="uq_jobs_url")

    with pytest.raises(JobAlreadyExistsError) as error_info:
        service.create_job(_build_job_create())

    assert error_info.value.constraint_name == "uq_jobs_url"
    assert str(error_info.value) == "A job with the same URL already exists."

    session.rollback.assert_called_once_with()
    session.commit.assert_not_called()
    session.refresh.assert_not_called()


def test_service_create_rolls_back_unexpected_error() -> None:
    """Verify unexpected creation failures are rolled back and preserved."""

    service, session, repository = _build_service()
